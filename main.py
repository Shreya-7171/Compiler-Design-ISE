
from lexer.lexer import Lexer
from parser.parser import Parser
from parser.tree_visualizer import TreeVisualizer
from semantic.semantic_analyzer import SemanticAnalyzer, SemanticError


# ---------------------------------------------------------
# SOURCE PROGRAM
# ---------------------------------------------------------

source_code = """START
MOVE FORWARD 10
TURN LEFT
PICK
WAIT 4
DROP
END
"""


print("=" * 60)
print("RCL COMPILER")
print("=" * 60)

print("\nSOURCE CODE")
print("-" * 60)
print(source_code)


# ---------------------------------------------------------
# PHASE 1: LEXICAL ANALYSIS
# ---------------------------------------------------------

print("=" * 60)
print("PHASE 1: LEXICAL ANALYSIS")
print("=" * 60)

lexer = Lexer(source_code)

tokens = lexer.tokenize()

for token in tokens:
    print(token)


# ---------------------------------------------------------
# PHASE 2: SYNTAX ANALYSIS
# ---------------------------------------------------------

print("\n" + "=" * 60)
print("PHASE 2: SYNTAX ANALYSIS")
print("=" * 60)

try:

    parser = Parser(tokens)

    # Parser generates the actual syntax tree
    tree = parser.parse()

    print("\nParsing successful!")
    print("Opening animated Parse Tree...")

    # Visualize the tree generated by parser
    visualizer = TreeVisualizer(tree)

    visualizer.run()

except SyntaxError as e:

    print("\nSyntax Error:")
    print(e)

    raise SystemExit


# ---------------------------------------------------------
# PHASE 3: SEMANTIC ANALYSIS
# ---------------------------------------------------------

print("\n" + "=" * 60)
print("PHASE 3: SEMANTIC ANALYSIS")
print("=" * 60)

try:

    semantic_analyzer = SemanticAnalyzer(tokens)

    semantic_analyzer.analyze()

    print("\nSemantic analysis successful!")

except SemanticError as e:

    print("\nSemantic Error:")
    print(e)

    raise SystemExit


# ---------------------------------------------------------
# FINAL RESULT
# ---------------------------------------------------------

print("\n" + "=" * 60)
print("COMPILATION SUCCESSFUL")
print("=" * 60)

